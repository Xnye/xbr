# 连体／并列助词：它们把两个词焊成一个成分，不能当词尾格助词处理。
#   の  连体（所属/属性）：駅の 外      → 车站的外面
#   と  并列（完全列举）：机と いす    → 桌子和椅子
#   や  并列（不完全列举）：机や いす  → 桌子和椅子等
#   な  な形容词的连体形（第9课起）：静かな 町 → 安静的 城市
#      —— な 本身不是格助词，它只把な形容词降级成修饰语；罗马音层不管它
#      （きれいな人形 仍写 kireina ningyou），这里只负责把短语合成一个成分。
LINKERS = {
    'の': {'join': '的', 'lit': '的'},
    'な': {'join': '的', 'lit': '的'},
    'と': {'join': '和', 'lit': '和'},
    'や': {'join': '和', 'lit': '和…等'},
}

# と／や 一身两职：并列（机といすが）vs 伴随（森さんと日本へ）。
# 并列的标志是整串最后落在主语/话题/宾语标记上（が/は/も/を），
# 或干脆直接接谓语；伴随的标志是后接 へ/で/から/まで 这类 adjunct 标记。
# 只在并列签名出现时合并，伴随一律保持拆开。
COORD_FINAL_OK = {'が', 'は', 'も', 'を'}


def _na_attributive(seg):
    """
    な形容词的连体形（静かな／きれいな）→ 词干＋连体助词 な。

    为什么要单独合成一个 な：罗马音层不能把 な 当助词剥出去
    （教材的读法是 kireina ningyou 一个词，C14 的回归用例钉着这个结果），
    但透视图里「静かな 町」必须是一个成分——否则 な 会像 の 那样被拍平，
    学习者会以为「静かな」是个独立的词。所以只在这一层补出 な。
    查不到词表就原样返回（让 gloss 走「な形容词（连体形）」那条路）。
    """
    if seg.get('kind') == 'punct' or seg.get('particle') or seg.get('predicate') \
            or seg.get('final') or seg.get('conj'):
        return seg
    body = seg.get('body') or ''
    if not body.endswith('な'):
        return seg
    dic, _form = M.adj_form(body)
    if not dic:
        return seg
    out = dict(seg)
    out['body'] = body[:-1]
    if (out.get('body_read') or '').endswith('な'):
        out['body_read'] = out['body_read'][:-1]
    out['particle'] = 'な'
    return out


def merge_attributive(segments):
    """
    把「连体/并列助词悬空段」并入后一个名词段，还原嵌套或并列的名词短语。

    の／な／と／や 都要求后接名词：段尾挂着它们而没有谓语，说明这个段不完整
    （「駅の」不是个东西，「駅の外」才是；「静かな」也不是，「静かな町」才是）。
    旧引擎按全角空格硬切，把嵌套/并列结构拍平成两个平级块，
    等于宣称 の/と 是前一个词的格助词——这是语法错误，不是显示偏好。

    合并条件刻意收紧：
      * 该段 particle 属于 LINKERS，且没有谓语、没有终助词
        （「スミスさんのです」带谓语 です，の 是名词化，不合并）
      * 后一段必须有名词词体（所以句尾的「静かな」不会被硬并）
      * と／や 还需整串收尾呈现并列签名（见 COORD_FINAL_OK），
        否则按伴随处理、保持拆开（第6课「森さんと日本へ」属此类）
    链式（AのBのC / AとBとC）通过循环自然折叠。
    """
    segments = list(segments)
    # 先给な形容词补出连体助词 な（只在后面确实跟着名词时补，见 _na_attributive）
    for k, seg in enumerate(segments):
        nxt = segments[k + 1] if k + 1 < len(segments) else None
        if nxt is None or nxt['kind'] == 'punct' or not (nxt.get('body') or ''):
            continue
        segments[k] = _na_attributive(seg)

    out = []
    i = 0
    n = len(segments)
    while i < n:
        seg = segments[i]
        if seg['kind'] == 'punct':
            out.append(seg)
            i += 1
            continue
        comps = [seg]
        while comps[-1].get('particle') in LINKERS \
                and not comps[-1].get('predicate') \
                and not comps[-1].get('final'):
            j = i + len(comps)
            nxt = segments[j] if j < n else None
            if nxt is None or nxt['kind'] == 'punct' or not (nxt.get('body') or ''):
                break
            comps.append(nxt)

        if len(comps) > 1 and not _is_coordination(comps):
            comps = [comps[0]]   # 伴随读法：不合并，退回单段
        out.append(compose_phrase(comps) if len(comps) > 1 else seg)
        i += len(comps) if len(comps) > 1 else 1
    return out


def _is_coordination(comps):
    """と／や 串起来的串，收尾必须是并列签名才合并；の／な 串无条件合并。"""
    linkers = [c.get('particle') for c in comps[:-1]]
    if all(l in ('の', 'な') for l in linkers):
        return True
    last = comps[-1]
    # 并列的标志：收尾落在主语／话题／宾语标记上（机といすが、コーラとケーキを）
    if last.get('particle') in COORD_FINAL_OK:
        return True
    # 收尾直接是谓语（コーラとケーキです）也是并列；
    # 但「友達と 帰りました」的收尾是动词（帰ります），那是伴随，不能合并。
    # 词表里 帰ります 是动词，这就是 §8.2 需要的自动判据。
    if last.get('predicate') and not last.get('particle') \
            and not M.verb_masu_form(last.get('body') or ''):
        return True
    return False


def compose_phrase(comps):
    """把多个被 の/と/や 串起来的段折叠成一个名词短语段。"""
    head = comps[-1]
    glosses = []
    for c in comps:
        g = M.gloss_of(c.get('body') or '') or {}
        glosses.append(g.get('zh') or c.get('body') or '')
    joined = glosses[0]
    for k, c in enumerate(comps[:-1]):
        joined += LINKERS[c['particle']]['join'] + glosses[k + 1]
    merged = dict(head)
    merged['phrase'] = True
    merged['components'] = comps
    merged['body'] = ''.join(
        c['body'] + (comps[k + 1] and c['particle'] or '') for k, c in enumerate(comps[:-1])
    ) + comps[-1]['body']
    merged['body_read'] = ''.join(
        c['body_read'] + c['particle'] for c in comps[:-1]
    ) + comps[-1]['body_read']
    merged['phrase_gloss'] = joined
    # 词级粒度要保住连接助词，也要把黏在词尾的助词剥出来：
    #   机の上 → ['つくえ', 'の', 'うえ'] → 块内罗马音 tsukue no ue
    # 词级粒度只按 ! 断词，助词常常黏在词尾（つくえの），所以这里手动拆一次。
    words = []
    for k, c in enumerate(comps):
        lk = c.get('particle') or ''
        ws = list(c.get('words') or [])
        if lk and ws and ws[-1].endswith(lk) and len(ws[-1]) > len(lk):
            ws[-1] = ws[-1][:-len(lk)]
        words.extend(ws)
        if k < len(comps) - 1 and lk:
            words.append(lk)
    merged['words'] = [w for w in words if w]
    return merged


def ruby_units_for(seg, body):
    """词体对应的振假名单元序列（不含助词）。"""
    return [{'type': 'ruby', 'kanji': p['kanji'], 'kana': p['kana']}
            for p in ruby_parts_for(seg, body)]


def body_romaji(seg):
    """词体部分的罗马音，保留 ! 给出的词界空格。"""
    body_read = seg.get('body_read') or ''
    if not body_read:
        return ''
    words = seg.get('words') or []
    if len(words) <= 1:
        return M._spaced_reading(body_read)
    out = []
    remain = body_read
    for w in words:
        if not remain:
            break
        if remain.startswith(w):
            out.append(M._spaced_reading(w))
            remain = remain[len(w):]
        else:
            out.append(M._spaced_reading(remain))
            remain = ''
    return ' '.join(x for x in out if x)


def ruby_parts_for(seg, body):
    """按词体长度截取 parts，拼出 <ruby> 所需的 kanji/kana 序列。"""
    if not body:
        return []
    parts = []
    remain = len(body)
    for p in seg.get('parts', []):
        if remain <= 0:
            break
        s = p['surf']
        if len(s) <= remain:
            parts.append({'kanji': s, 'kana': p['read'] if p.get('ann') else ''})
            remain -= len(s)
        else:
            parts.append({'kanji': s[:remain], 'kana': ''})
            remain = 0
    return parts


def build_chunks(segments):
    """
    把分析后的语块段编译成 diagram.js 需要的 chunks 数组。
    每段最多产出三个 chunk：词体（带助词框）、谓语、终助词。
    """
    chunks = []
    n = 0

    def nid():
        nonlocal n
        n += 1
        return 'c%d' % n

    prev_te = False          # 上一段是不是动词て形（供「〜て ください」判断）
    for seg in segments:
        if seg['kind'] == 'punct':
            continue
        seg_te = seg.get('predicate_inner') == 'て'
        if seg['kind'] == 'punct':
            continue

        # --- 词体 + 助词 ---
        body = seg.get('body') or ''
        if body:
            pname = seg.get('particle') or ''
            # 助词 'か' 走到这里一定是「并列・不定」用法（句尾疑问的 か 已被 final 剥走），
            # 所以用 PARTICLES_NONFINAL 的那套名称／颜色／说明。
            meta = M.PARTICLES_NONFINAL.get(pname) or M.PARTICLES.get(pname, {})
            chunk = {
                'id': nid(),
                'text': body,
                'romaji': body_romaji(seg),
                'particle': seg.get('particle') or '',
                'particle_color': meta.get('color', 'none'),
                'particle_name': meta.get('name', ''),
                'particle_desc': meta.get('desc', ''),
                'underline_color': meta.get('color', 'none'),
                'underline_span': 'full',
                'src_seg': seg['surf'],
                'kind': 'body',
            }

            if seg.get('phrase'):
                # 名词短语（駅の 外 / 机の 上 / JC企画の 社員）：
                # の 渲染成块内连接框，不再冒充词尾格助词；
                # gloss 是整个短语的含义，直译行也按短语整体出 token。
                comps = seg['components']
                units = []
                lit = []
                for ci, c in enumerate(comps):
                    units.extend(ruby_units_for(c, c['body']))
                    cg = M.gloss_of(c['body']) or {}
                    lit.append({'text': cg.get('zh') or c['body'],
                                'color': 'normal', 'underline': False})
                    if ci < len(comps) - 1:
                        lk = c['particle']
                        nmeta = M.PARTICLES[lk]
                        units.append({'type': 'box', 'particle': lk,
                                      'color': nmeta['color'],
                                      'name': nmeta['name'], 'desc': nmeta['desc']})
                        lit.append({'text': LINKERS[lk]['lit'], 'color': nmeta['color'],
                                    'underline': True, 'target_chunk': chunk['id']})
                chunk['jp_units'] = units
                chunk['lit_tokens'] = lit
                chunk['gloss_main'] = seg['phrase_gloss']
                chunk['gloss_sub'] = '名词短语'
                chunk['phrase'] = True
            else:
                g = M.gloss_of(body, prefer_verb=bool(seg.get('inflection'))) or {}
                chunk['gloss_main'] = g.get('zh') or body
                chunk['gloss_sub'] = g.get('pos') or ''
                rp = ruby_parts_for(seg, body)
                if rp and any(p['kana'] for p in rp):
                    chunk['ruby_parts'] = rp
                elif rp and len(rp) == 1:
                    chunk['ruby'] = rp[0]['kana']
            chunks.append(chunk)

        # --- 内层谓语尾：い形容词活用（楽し＋かった／熱く＋ない）---
        # 顺序必须是先内层后外层：楽し → かった → です，读者才能顺着看见活用怎么长出来。
        inner = seg.get('predicate_inner')
        if inner:
            zh, note, color, _lit = M.predicate_info(inner)
            chunks.append({
                'id': nid(),
                'text': inner,
                'romaji': M._spaced_reading(inner),
                'gloss_main': zh,
                'gloss_sub': note,
                'particle': '',
                'particle_color': 'none',
                'particle_name': '',
                'particle_desc': '',
                'underline_color': color,
                'underline_span': 'full',
                'kind': 'predicate',
                'inflection': bool(seg.get('inner_inflection')),
                'src_seg': seg['surf'],
            })

        # --- 谓语 ---
        pred = seg.get('predicate')
        if pred:
            zh, note, color, _lit = M.predicate_info(pred)
            if pred == 'ください' and (seg_te or prev_te):
                zh = '请（做）'          # て形＋ください：请对方做某事（不是「给我」）
            chunks.append({
                'id': nid(),
                'text': pred,
                'romaji': M._spaced_reading(pred),
                'gloss_main': zh,
                'gloss_sub': note,
                'particle': '',
                'particle_color': 'none',
                'particle_name': '',
                'particle_desc': '',
                'underline_color': color,
                'underline_span': 'full',
                'kind': 'predicate',
                'inflection': bool(seg.get('inflection')),
                'src_seg': seg['surf'],
            })

        # --- 接续助词：挂在谓语之后的 から／が（好きですから／有料ですが）---
        conj = seg.get('conj')
        if conj:
            cmeta = M.PARTICLES.get(conj, {})
            chunks.append({
                'id': nid(),
                'text': conj,
                'romaji': M._spaced_reading(conj),
                'gloss_main': ('之后' if (conj == 'から' and (seg_te or prev_te))
                               else (CONJ_LIT.get(conj) or cmeta.get('gloss', conj))),
                'gloss_sub': ('接续助词（てから＝之后）' if (conj == 'から' and (seg_te or prev_te))
                              else '接续助词（挂在谓语之后）'),
                'particle': '',
                'particle_color': 'none',
                'particle_name': '',
                'particle_desc': cmeta.get('desc', ''),
                'underline_color': cmeta.get('color', 'cyan'),
                'underline_span': 'full',
                'kind': 'conj',
                'src_seg': seg['surf'],
            })

        # --- 终助词 ---
        fin = seg.get('final')
        if fin:
            fmeta = M.PARTICLES.get(fin, {})
            chunks.append({
                'id': nid(),
                'text': fin,
                'romaji': M._spaced_reading(fin),
                'gloss_main': FINAL_LIT.get(fin, fin),
                'gloss_sub': fmeta.get('name', '终助词'),
                'particle': '',
                'particle_color': 'none',
                'particle_name': '',
                'particle_desc': fmeta.get('desc', ''),
                'underline_color': fmeta.get('color', 'slate'),
                'underline_span': 'full',
                'kind': 'final',
                'src_seg': seg['surf'],
            })
        prev_te = seg_te          # 只认动词て形：供「〜て ください」「てから」判断

    return chunks


def build_literal(segments, chunks):
    """
    生成逐词中文直译行。严格保持日语语序，
    助词的直译词按 LIT 表前置或后置，颜色与透视图助词框一致以便悬停联动。
    """
    ci = iter(chunks)
    clauses = []
    cur = []
    # 同句谓语（词体读法＋活用尾巴）——用来判断 を 是宾语还是起点／经过
    verbs = [(s.get('body_read') or '') + (s.get('predicate') or '')
             for s in segments if s.get('predicate')]

    def tok(text, color='normal', underline=False, target=None):
        t = {'text': text, 'color': color, 'underline': underline}
        if target:
            t['target_chunk'] = target
        return t

    for seg in segments:
        if seg['kind'] == 'punct':
            if seg['surf'] in ('，', '、'):
                clauses.append(cur)
                cur = []
            continue

        body = seg.get('body') or ''
        part = seg.get('particle')
        inner = seg.get('predicate_inner')
        pred = seg.get('predicate')
        conj = seg.get('conj')
        fin = seg.get('final')

        # chunk 的消费顺序必须与 build_chunks 的产出顺序一致：
        # 词体 → 内层谓词尾（かった／ない）→ 外层谓词尾（です…）→ 接续助词 → 终助词
        body_chunk = next(ci, None) if body else None
        inner_chunk = next(ci, None) if inner else None
        pred_chunk = next(ci, None) if pred else None
        conj_chunk = next(ci, None) if conj else None
        fin_chunk = next(ci, None) if fin else None

        lit = LIT.get(part or '', {'pre': '', 'post': ''})
        if part == 'で':
            # 場所で（在）与 手段で（用）：直译词看名词本身是不是"地方"
            lit = {'pre': _de_literal(body), 'post': ''}
        elif part == 'を':
            # を 是宾语还是起点／经过，看同句谓语（家を 出ます → 从；公園を 散歩します → 在）
            lit = {'pre': _wo_literal(verbs), 'post': ''}
        elif part == 'に':
            # 数量词＋に 是计数基准（一週間に 二回＝每）；动词ます形＋に 是移动目的（出しに 行きます）
            if M.counter_gloss(body):
                lit = {'pre': '每', 'post': ''}
            elif M.verb_masu_form(body) or M.suru_verb_base(body):
                lit = {'pre': '去', 'post': ''}
        color_meta = M.PARTICLES_NONFINAL.get(part or '') or M.PARTICLES.get(part or '', {})
        color = color_meta.get('color', 'normal')
        g = M.gloss_of(body, prefer_verb=bool(seg.get('inflection'))) if body else None
        body_zh = (g or {}).get('zh') or body

        if part and lit['pre']:
            cur.append(tok(lit['pre'], color, True, body_chunk['id'] if body_chunk else None))

        if body_chunk:
            if body_chunk.get('lit_tokens'):
                # 名词短语：直译行按「修饰语 的 中心语」出多个 token，
                # 保持短语作为一个整体，不再被拍平成两个平级词
                cur.extend(body_chunk['lit_tokens'])
            else:
                # 助词无直译词时（如 が），把颜色直接打在名词本体上，保住联动
                body_color = color if (part and not lit['pre'] and not lit['post']) else 'normal'
                cur.append(tok(body_zh, body_color, bool(part and not lit['pre'] and not lit['post']),
                               body_chunk['id'] if part else None))

        if part and lit['post']:
            cur.append(tok(lit['post'], color, True, body_chunk['id'] if body_chunk else None))

        if inner_chunk:
            # 内层谓词尾（い形容词活用）：楽し＋かった／熱く＋ない。
            # 直译行用「（过去）／不」这类短词义，跟外层谓词保持一致。
            cur.append(tok(M.predicate_info(inner)[3], 'green', True, inner_chunk['id']))

        if pred_chunk:
            # 直译行用短词义（PREDICATES 第4项）。「有・在（人/动物）」这种
            # 完整词义放在词下注释框里合适，塞进逐词直译行会把整行撑爆。
            cur.append(tok(M.predicate_info(pred)[3], 'green', True, pred_chunk['id']))

        if conj_chunk:
            # てから：から 挂在て形后面，直译是「之后」；单纯谓语的 から 才是「因为」
            ctext = '之后' if (conj == 'から' and inner == 'て') else CONJ_LIT.get(conj, conj)
            cur.append(tok(ctext, 'cyan', True, conj_chunk['id']))

        if fin_chunk:
            cur.append(tok(FINAL_LIT.get(fin, fin), 'slate', True, fin_chunk['id']))

    clauses.append(cur)
    return [{'clause': i + 1, 'tokens': c} for i, c in enumerate(clauses) if c]


def infer_zero_subject(segments, chunks, clean):
    """
    推理深层主语（零代词）。三种情形：
      1. 出现显式 が → 主语已surface，不显示 Ø が（存在句属此类）
      2. 出现 は／も 话题 → Ø が 与话题同指：は 把 が 吸收了
      3. 两者都没有 → 依谓语类型推断（です→听话人，其他→说话人）
    """
    has_ga = any(s.get('particle') == 'が' for s in segments if s['kind'] != 'punct')
    if has_ga:
        return None

    topic_seg = next((s for s in segments
                      if s['kind'] != 'punct' and s.get('particle') in ('は', 'も')), None)
    if topic_seg:
        topic_chunk = next((c for c in chunks if c.get('src_seg') == topic_seg['surf']), None)
        if not topic_chunk:
            return None
        g = M.gloss_of(topic_seg.get('body') or '') or {}
        topic_zh = g.get('zh') or topic_seg.get('body') or ''
        # 提示里要写「X が …」的完整深层结构：把话题段去掉，用其余段的字面拼出来。
        # 不能用 clean——analyze_sentence 的 clean 不带语块空格（全角空格被当分隔符吃掉了）。
        rest = ''.join(s['surf'] for s in segments
                       if s['kind'] != 'punct' and s is not topic_seg)
        return {
            'symbol': 'Ø',
            'particle': 'が',
            'tooltip': ZERO_TOOLTIP_ABSORED.format(topic=topic_seg.get('body', ''), rest=rest),
            'targets': [{'id': topic_chunk['id'], 'label': '%s（＝话题，は 吸收了 が）' % topic_zh}],
        }
    pred_seg = next((s for s in segments
                     if s['kind'] != 'punct' and s.get('predicate')), None)
    if not pred_seg:
        return None
    pred = pred_seg.get('predicate') or ''
    is_question = bool(pred_seg.get('final')) or pred.endswith('か')
    has_particle = any(s.get('particle') for s in segments if s['kind'] != 'punct')
    if pred in ('です', 'でした') and not has_particle:
        # 时刻／状态句（今四時です／明日です）：深层"主语"是当前情况而不是人，
        # 硬标成"我"会教错，所以这里不显示 Ø が。
        return None
    if is_question:
        subject = '听话人（你）'
    elif pred in ('ください', 'ましょう', 'ませんか'):
        # 请求／劝诱：当事者是听话人或双方
        subject = '听话人（你）' if pred == 'ください' else '我们（双方）'
    else:
        subject = '说话人（我）'
    target = next((c for c in chunks if c.get('kind') == 'predicate'), None)
    if not target:
        return None
    return {
        'symbol': 'Ø',
        'particle': 'が',
        'tooltip': ZERO_TOOLTIP_IMPLICIT.format(subject=subject),
        'targets': [{'id': target['id'], 'label': subject}],
    }


def _patched_raw(raw):
    """透视图与罗马音数据层必须用**同一份修订过的句面**（build_romaji.SOURCE_PATCHES）。
    否则教材注音错字（如第13课 一週間(いちしゅうかん)）会让两边算出不同的罗马音，
    C14 会直接报「透视图整句罗马音与数据层不一致」。"""
    try:
        import build_romaji as B
        return B.patch_raw(raw)[0]
    except Exception:
        return raw


def build_exemplar(lesson_num, sentence_id, b4, lesson_title):
    """为一句基本课文生成一条透视图数据。"""
    analysis = M.analyze_sentence(_patched_raw(b4['jp_raw']))
    # 先还原 の 串起来的嵌套名词短语，再做块级编译；
    # 否则「駅の／外に」会被切成两个平级块，把嵌套结构拍平。
    segments = merge_attributive(analysis['segments'])
    clean = analysis['clean']
    romaji = analysis['romaji']

    chunks = build_chunks(segments)
    literal = build_literal(segments, chunks)
    zero = infer_zero_subject(segments, chunks, clean)

    tag, title = SENTENCE_META.get(sentence_id, ('第%d课' % lesson_num, lesson_title))
    note = COGNITIVE_NOTES.get(sentence_id)
    if not note:
        raise SystemExit('缺少 %s 的认知心法（cognitive_note 必须手写，不自动生成）' % sentence_id)

    zh = (b4.get('zh') or '').lstrip('*').strip()

    ex = {
        'id': sentence_id,
        'lesson': lesson_num,
        'is_featured': False,
        'auto_generated': True,
        'tag': tag,
        'lesson_title': title,
        'sentence_raw': clean,
        'sentence_romaji': romaji,
        'source_id': b4.get('id'),
        'natural_translation': zh,
    }
    if zero:
        ex['zero_subject'] = zero
    ex['chunks'] = chunks
    ex['literal_structure'] = literal
    ex['cognitive_note'] = note
    return ex


# 已覆盖的课（引擎生成透视图的范围）。扩课就改这里，
# 但必须先给该课每一句补上手写认知心法与 SENTENCE_META，否则构建会直接报错。
# 第 9～12 课是形容词（い／な形容词的 です・でした・くない・かった 与比较表达），
# 第 13 课是数量词（时间段／基准 に）、第 14 课是て形（て／てから／てください／目的の に）。
# 引擎侧的表：ADJ_I_TAILS／adj_form（形容词）、TE_TAILS／_te_stem_masu（て形）、
#            COUNTERS／counter_gloss（数量词）。
COVERED_LESSONS = range(1, 15)

def main():
    covered = COVERED_LESSONS
    if len(sys.argv) > 2 and sys.argv[1] == '--lessons':
        spec = sys.argv[2]
        if '-' in spec:
            a, b = spec.split('-')
            covered = range(int(a), int(b) + 1)
        else:
            covered = [int(x) for x in spec.split(',')]

    with io.open(LESSONS_PATH, encoding='utf-8') as f:
        lessons = json.load(f)

    existing = []
    if os.path.exists(EXEMPLARS_PATH):
        with io.open(EXEMPLARS_PATH, encoding='utf-8') as f:
            existing = json.load(f)
    preserved = [apply_legacy_fixup(
                     localize_showcase(e) if e['id'] == 'screenshot_showcase' else e)
                 for e in existing if e['id'] in PRESERVE_IDS]

    generated = []
    for les in lessons:
        n = les['number']
        if n not in covered:
            continue
        title = les.get('title_clean', '')
        for i, b4 in enumerate(les.get('basic4') or [], start=1):
            sid = 'l%d_b%d' % (n, i)
            generated.append(build_exemplar(n, sid, b4, title))

    # 未被本轮覆盖、也不在保留名单里的旧条目一并保留，避免误删后续课程的人工成果
    covered_ids = {e['id'] for e in generated} | PRESERVE_IDS
    others = [apply_legacy_fixup(localize_other(e))
              for e in existing if e['id'] not in covered_ids]

    out = preserved + others + generated
    out.sort(key=lambda e: (e.get('lesson', 0), e['id']))

    with io.open(EXEMPLARS_PATH, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, indent=2)

    # ---------------- 自检 ----------------
    problems = []
    for e in generated:
        if not e['chunks']:
            problems.append('%s: 没有 chunk' % e['id'])
        for c in e['chunks']:
            if c.get('particle') and not c.get('particle_color'):
                problems.append('%s: 助词 %s 缺颜色' % (e['id'], c['particle']))
            if c['text'] and not c.get('gloss_main'):
                problems.append('%s: %s 缺词义' % (e['id'], c['text']))
            if not c.get('romaji'):
                problems.append('%s: %s 缺罗马音' % (e['id'], c['text']))
        ids = [c['id'] for c in e['chunks']]
        if e.get('zero_subject'):
            for t in e['zero_subject']['targets']:
                if t['id'] not in ids:
                    problems.append('%s: Ø が 箭头指向不存在的 chunk %s' % (e['id'], t['id']))
        for cl in e['literal_structure']:
            if not cl['tokens']:
                problems.append('%s: 第%d小句直译行为空' % (e['id'], cl['clause']))
            for t in cl['tokens']:
                if t.get('target_chunk') and t['target_chunk'] not in ids:
                    problems.append('%s: 直译 token 指向不存在的 chunk %s' % (e['id'], t['target_chunk']))

    print('已生成 %s' % EXEMPLARS_PATH)
    print('  保留手写条目 : %d' % len(preserved))
    print('  引擎生成条目 : %d（覆盖第 %s 课基本课文）'
          % (len(generated), ','.join(str(x) for x in covered)))
    print('  其他旧条目   : %d' % len(others))
    print('  合计         : %d' % len(out))
    zero_cnt = sum(1 for e in generated if e.get('zero_subject'))
    print('  含零主语推理 : %d / %d' % (zero_cnt, len(generated)))
    if problems:
        print('\n!! 自检发现 %d 个问题：' % len(problems))
        for p in problems:
            print('   -', p)
        raise SystemExit(1)
    print('  自检         : 通过（chunk/助词色/词义/罗马音/箭头锚点/直译行 全项）')


if __name__ == '__main__':
    main()
