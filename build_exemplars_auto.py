# で 的直译词要分两种：场所用「在」，手段／材料用「用」。
# 判据看那个名词本身是不是"地方"（図書館で…在图书馆／新幹線で…用新干线）。
_PLACE_TAIL = ('館', '室', '店', '場', '園', '校', '院', '家', '駅', '屋', '部', '所', '社',
               '堂', '国', '市', '町', '村', '台', '地', 'うち', 'デパート', 'スーパー',
               'レストラン', 'ホテル', 'アパート', '会社', '学校', '大学')


def _de_literal(body):
    if not body:
        return '在'
    return '在' if any(body.endswith(t) for t in _PLACE_TAIL) else '用'


# を 的两副面孔：宾语（把）vs 移动的起点／经过（从／在）。判据是同句的谓语动词：
#   家を 出ます／大学を 卒業します → 起点 →「从」
#   公園を 散歩します／道を 渡ります／空を 飛びます → 经过的场所 →「在」
_WO_SOURCE_VERBS = ('でます', 'そつぎょうします', 'おりります')
_WO_PATH_VERBS = ('とおります', 'わたります', 'さんぽします', 'あるきます', 'はしります', 'とびます')


def _wo_literal(verbs):
    if any(v in _WO_SOURCE_VERBS for v in verbs):
        return '从'
    if any(v in _WO_PATH_VERBS for v in verbs):
        return '在'
    return '把'
