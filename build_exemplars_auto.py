def apply_legacy_fixup(out):
    """套用 LEGACY_FIXUP：助词名中文化、Ø が 锚点纠正、tooltip 去英文。"""
    spec = _legacy_fixup().get(out.get('id'))
    if not spec:
        return out
    for c in out.get('chunks', []):
        nm = (spec.get('particle_name') or {}).get(c.get('text'))
        if nm:
            c['particle_name'] = nm
        ds = (spec.get('particle_desc') or {}).get(c.get('text'))
        if ds:
            c['particle_desc'] = ds
    z = out.get('zero_subject')
    if z:
        if spec.get('zero_tooltip'):
            z['tooltip'] = spec['zero_tooltip']
        if spec.get('zero_targets'):
            z['targets'] = [{'id': i, 'label': lb} for i, lb in spec['zero_targets']]
    return out


