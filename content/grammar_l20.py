def _merge_why(entries):
    """把若干要点段合并为两段，保持前端阅读节奏，不删内容。"""
    for entry in entries:
        parts = entry['why']
        mid = (len(parts) + 1) // 2
        merged = []
        for chunk in (parts[:mid], parts[mid:]):
            text = ''.join(chunk).strip()
            if text and text[-1] not in '。！？':
                text += '。'
            merged.append(text)
        entry['why'] = merged


_merge_why(ENTRIES)
